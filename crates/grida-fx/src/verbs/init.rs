use serde_json::{Value, json};
use std::fs::OpenOptions;
use std::io::{self, BufRead, IsTerminal, Read, Write};
use std::path::{Component, Path, PathBuf};
use std::time::Duration;

/// The built-in starter, in the order it is written. Dotfiles are stored without their dot so
/// that they do not act on this repository.
const STARTER: [(&str, &str); 6] = [
    ("fx.yaml", include_str!("../../templates/init/fx.yaml")),
    ("README.md", include_str!("../../templates/init/README.md")),
    ("AGENTS.md", include_str!("../../templates/init/AGENTS.md")),
    (".gitignore", include_str!("../../templates/init/gitignore")),
    (
        ".env.example",
        include_str!("../../templates/init/env.example"),
    ),
    (
        "workflows/icon.yaml",
        include_str!("../../templates/init/workflows/icon.yaml"),
    ),
];

// Every agent skill of the repository's `skills/`, as `npx skills add gridaco/fx` installs them:
// every project `init` starts gets them, the starter and every template (spec/service.md §2).
// Generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/skills.rs"));

/// The built-in starter's name and description in the listing.
const STARTER_NAME: &str = "starter";
const STARTER_DESCRIPTION: &str =
    "A one-step workflow that draws an icon once you pick a provider (built in, offline)";

/// The templates of the commit this engine was built from (spec/service.md §2.1).
const INDEX: &str = include_str!("../../../../examples/templates.json");

/// Entries that leave a directory empty for `init`: a fresh `git init`, and Finder's metadata.
const IGNORED: [&str; 2] = [".git", ".DS_Store"];

/// What a directory source skips wherever it occurs, so that it yields what the archive would.
const SKIPPED: [&str; 8] = [
    ".git",
    ".fx",
    "runs",
    ".venv",
    "node_modules",
    "__pycache__",
    ".showcase-inputs",
    ".env",
];

/// The limits on a download and on a template (spec/service.md §2.1).
const MAX_DOWNLOAD: u64 = 64 * 1024 * 1024;
const MAX_FILES: usize = 1000;
const MAX_UNPACKED: u64 = 32 * 1024 * 1024;
const DOWNLOAD_TIMEOUT: Duration = Duration::from_secs(300);

/// One entry of `examples/templates.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Template {
    pub name: String,
    pub description: String,
    pub provider: String,
    pub path: String,
}

/// The embedded index, in order. A malformed index is a fault of the build, not of the user.
pub fn templates() -> Result<Vec<Template>, Error> {
    let index: Value = serde_json::from_str(INDEX)
        .map_err(|_| Error::internal("examples/templates.json is not JSON"))?;
    let entries = index
        .get("templates")
        .and_then(Value::as_array)
        .ok_or_else(|| Error::internal("examples/templates.json has no templates list"))?;
    let mut found: Vec<Template> = Vec::new();
    for entry in entries {
        let text = |key: &str| {
            entry
                .get(key)
                .and_then(Value::as_str)
                .map(str::to_string)
                .ok_or_else(|| Error::internal(format!("a template has no {key}")))
        };
        let template = Template {
            name: text("name")?,
            description: text("description")?,
            provider: text("provider")?,
            path: text("path")?,
        };
        let named = !template.name.is_empty()
            && template
                .name
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
        let placed = template.path.starts_with("examples/")
            && relative_parts(&template.path).is_some_and(|parts| parts.len() == 2);
        if !named
            || template.name == STARTER_NAME
            || !placed
            || !["none", "codex", "gg", "any"].contains(&template.provider.as_str())
            || found.iter().any(|other| other.name == template.name)
        {
            return Err(Error::internal(format!(
                "examples/templates.json: template {:?} is malformed",
                template.name
            )));
        }
        found.push(template);
    }
    Ok(found)
}

/// The release archive an engine of this version reads its templates from.
pub fn release_url() -> String {
    format!("https://codeload.github.com/gridaco/fx/tar.gz/v{ENGINE_VERSION}")
}

/// What `init` starts a project from.
enum Choice {
    Starter,
    Template(Template),
}

pub fn init(args: &InitArgs) -> Result<u8, Error> {
    if args.list_templates {
        return list(args.json);
    }
    let root = Path::new(args.directory.as_deref().unwrap_or("."));
    let path = root.join("fx.yaml");
    if std::fs::symlink_metadata(&path).is_ok() {
        if !path.is_file() {
            return Err(Error::usage(
                "fx.yaml exists but is not a project file; nothing was overwritten",
            ));
        }
        if args.template.is_some() {
            return Err(Error::usage(
                "this directory is already a project (it has fx.yaml); --template starts a new \
                 project in an empty directory",
            ));
        }
        // Validate an existing configuration without replacing or normalizing it.
        let project = Project::find(root)?;
        return report(args, &project, None, &[]);
    }
    if !is_empty(root)? {
        let named = args.directory.as_deref().unwrap_or("this directory");
        return Err(Error::usage(format!(
            "{named} is not empty and has no fx.yaml; init starts a new project in an empty \
             directory. To make an existing folder a project, create fx.yaml holding \
             `fx: project/v1`"
        )));
    }
    let choice = match &args.template {
        Some(name) => choose(name)?,
        None if interactive(args) => pick()?,
        None => Choice::Starter,
    };
    let created_root = !root.exists();
    std::fs::create_dir_all(root).map_err(|error| Error::io("project directory", &error))?;
    let outcome = match &choice {
        Choice::Starter => write_starter(root).map(|files| (files, "built_in")),
        Choice::Template(template) => {
            write_template(root, template, args.template_source.as_deref())
        }
    };
    let (files, source) = match outcome {
        Ok(outcome) => outcome,
        Err(error) => {
            if created_root {
                let _ = std::fs::remove_dir(root);
            }
            return Err(error);
        }
    };
    let project = Project::find(root)?;
    let name = match &choice {
        Choice::Starter => STARTER_NAME,
        Choice::Template(template) => template.name.as_str(),
    };
    report(args, &project, Some((name, source)), &files)
}

/// Prints the outcome (spec/service.md §5): what was written, and what to do next.
fn report(
    args: &InitArgs,
    project: &Project,
    started: Option<(&str, &str)>,
    files: &[String],
) -> Result<u8, Error> {
    let command = crate::invoker::command();
    if args.json {
        let template = started.map(|(name, source)| json!({"name": name, "source": source}));
        println!(
            "{}",
            json!({
                "kind": "fx-project-init-v1", "created": started.is_some(),
                "project_root": project.root, "files_created": files, "template": template,
            })
        );
        return Ok(0);
    }
    let Some((name, _)) = started else {
        println!("Using existing fx.yaml");
        println!("Start the local service with {command} start --background.");
        return Ok(0);
    };
    if name == STARTER_NAME {
        let own: Vec<&str> = files
            .iter()
            .map(String::as_str)
            .filter(|file| !file.starts_with(".agents/"))
            .collect();
        println!(
            "Created {}, and the FX agent skills in .agents/skills/",
            own.join(", ")
        );
    } else {
        println!("Created the {name} template ({} files)", files.len());
    }
    println!("Read README.md to install FX and connect an AI provider, then:");
    if let Some(directory) = &args.directory {
        println!("  cd {directory}");
    }
    if name == STARTER_NAME {
        println!("  {command} plan icon");
    } else {
        println!("  {command} plan <workflow>   (README.md names them)");
    }
    Ok(0)
}

fn list(as_json: bool) -> Result<u8, Error> {
    let templates = templates()?;
    if as_json {
        let mut listed = vec![json!({
            "name": STARTER_NAME, "description": STARTER_DESCRIPTION,
            "provider": "any", "source": "built_in",
        })];
        listed.extend(templates.iter().map(|template| {
            json!({
                "name": template.name, "description": template.description,
                "provider": template.provider, "source": "release",
            })
        }));
        println!(
            "{}",
            json!({"kind": "fx-project-templates-v1", "version": ENGINE_VERSION, "templates": listed})
        );
    } else {
        for (name, description) in std::iter::once((STARTER_NAME, STARTER_DESCRIPTION)).chain(
            templates
                .iter()
                .map(|template| (template.name.as_str(), template.description.as_str())),
        ) {
            println!("{name:<16} {description}");
        }
    }
    Ok(0)
}

fn choose(name: &str) -> Result<Choice, Error> {
    if name == STARTER_NAME {
        return Ok(Choice::Starter);
    }
    let templates = templates()?;
    match templates.iter().find(|template| template.name == name) {
        Some(template) => Ok(Choice::Template(template.clone())),
        None => {
            let names: Vec<&str> = std::iter::once(STARTER_NAME)
                .chain(templates.iter().map(|template| template.name.as_str()))
                .collect();
            Err(Error::usage(format!(
                "no template {name:?}; the templates: {}",
                names.join(", ")
            )))
        }
    }
}

/// Whether to ask which template (spec/service.md §2): only a person at a terminal, never an
/// agent, a script or CI.
fn interactive(args: &InitArgs) -> bool {
    !args.json
        && std::env::var_os("CI").is_none()
        && io::stdin().is_terminal()
        && io::stdout().is_terminal()
}

fn pick() -> Result<Choice, Error> {
    let templates = templates()?;
    println!("Start from which template?");
    println!("  0  {STARTER_NAME:<16} {STARTER_DESCRIPTION}");
    for (number, template) in templates.iter().enumerate() {
        println!(
            "  {:<2} {:<16} {}",
            number + 1,
            template.name,
            template.description
        );
    }
    print!("Template [0]: ");
    io::stdout()
        .flush()
        .map_err(|error| Error::io("terminal", &error))?;
    let mut answer = String::new();
    io::stdin()
        .lock()
        .read_line(&mut answer)
        .map_err(|error| Error::io("terminal", &error))?;
    let answer = answer.trim();
    if answer.is_empty() || answer == "0" {
        return Ok(Choice::Starter);
    }
    if let Ok(number) = answer.parse::<usize>()
        && let Some(template) = number.checked_sub(1).and_then(|index| templates.get(index))
    {
        return Ok(Choice::Template(template.clone()));
    }
    choose(answer)
}

/// Whether `root` is missing or holds nothing but [`IGNORED`] entries.
fn is_empty(root: &Path) -> Result<bool, Error> {
    let entries = match std::fs::read_dir(root) {
        Ok(entries) => entries,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(true),
        Err(error) => return Err(Error::io("project directory", &error)),
    };
    for entry in entries {
        let entry = entry.map_err(|error| Error::io("project directory", &error))?;
        if !IGNORED.iter().any(|name| entry.file_name() == *name) {
            return Ok(false);
        }
    }
    Ok(true)
}

/// The starter's files, then the skills', as `(project path, contents)`.
fn starter_files() -> impl Iterator<Item = (&'static str, &'static [u8])> {
    STARTER
        .iter()
        .map(|(name, contents)| (*name, contents.as_bytes()))
        .chain(SKILLS.iter().copied())
}

fn write_starter(root: &Path) -> Result<Vec<String>, Error> {
    for (name, contents) in starter_files() {
        write_new(&root.join(name), contents, name)?;
    }
    Ok(starter_files().map(|(name, _)| name.to_string()).collect())
}

/// Writes a file that must not exist yet, with its folders.
fn write_new(file: &Path, contents: &[u8], label: &str) -> Result<(), Error> {
    if let Some(parent) = file.parent() {
        std::fs::create_dir_all(parent).map_err(|error| Error::io("project directory", &error))?;
    }
    OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(file)
        .and_then(|mut handle| handle.write_all(contents))
        .map_err(|error| Error::io(label, &error))
}

/// Where a template's files come from (spec/service.md §2.1).
enum Source {
    Release(String),
    Url(String),
    Archive(PathBuf),
    Directory(PathBuf),
}

impl Source {
    fn of(given: Option<&str>) -> Result<Source, Error> {
        let Some(given) = given else {
            return Ok(Source::Release(release_url()));
        };
        if given.starts_with("http://") || given.starts_with("https://") {
            let url = url::Url::parse(given)
                .map_err(|_| Error::usage("--template-source is not a valid URL"))?;
            if url.scheme() == "http" && !loopback(&url) {
                return Err(Error::usage(
                    "--template-source must use https unless it targets a loopback host",
                ));
            }
            return Ok(Source::Url(given.to_string()));
        }
        let path = PathBuf::from(given);
        if path.is_dir() {
            Ok(Source::Directory(path))
        } else if path.is_file() {
            Ok(Source::Archive(path))
        } else {
            Err(Error::usage(
                "--template-source names no directory, archive or URL",
            ))
        }
    }

    /// `release` or `local`, as the init result names it.
    fn kind(&self) -> &'static str {
        match self {
            Source::Release(_) => "release",
            _ => "local",
        }
    }
}

fn loopback(url: &url::Url) -> bool {
    match url.host() {
        Some(url::Host::Domain(domain)) => domain
            .trim_end_matches('.')
            .eq_ignore_ascii_case("localhost"),
        Some(url::Host::Ipv4(ip)) => ip.is_loopback(),
        Some(url::Host::Ipv6(ip)) => ip.is_loopback(),
        None => false,
    }
}

/// Unpacks `template` into a hidden folder inside `root`, adds the starter's files it lacks, and
/// moves it into place. On a failure nothing of it remains.
fn write_template(
    root: &Path,
    template: &Template,
    given: Option<&str>,
) -> Result<(Vec<String>, &'static str), Error> {
    let source = Source::of(given)?;
    let staging = tempfile::Builder::new()
        .prefix(".fx-init-")
        .tempdir_in(root)
        .map_err(|error| Error::io("project directory", &error))?;
    let unpacked = staging.path();
    let mut limits = Limits::default();
    match &source {
        Source::Directory(directory) => {
            let folder = directory.join(&template.path);
            if !folder.is_dir() {
                return Err(missing(template));
            }
            copy_tree(&folder, unpacked, Path::new(""), &mut limits)?;
        }
        Source::Archive(path) => {
            let bytes = std::fs::read(path).map_err(|error| Error::io("the archive", &error))?;
            unpack(&bytes, template, unpacked, &mut limits)?;
        }
        Source::Url(url) | Source::Release(url) => {
            let bytes = download(url)?;
            unpack(&bytes, template, unpacked, &mut limits)?;
        }
    }
    if !unpacked.join("fx.yaml").is_file() {
        return Err(Error::new(
            ErrorKind::Io,
            format!("the {} template holds no fx.yaml", template.name),
        ));
    }
    overlay(unpacked)?;
    let mut files = Vec::new();
    list_files(unpacked, Path::new(""), &mut files)?;
    files.sort();
    for entry in std::fs::read_dir(unpacked).map_err(|error| Error::io("the template", &error))? {
        let entry = entry.map_err(|error| Error::io("the template", &error))?;
        std::fs::rename(entry.path(), root.join(entry.file_name()))
            .map_err(|error| Error::io("project directory", &error))?;
    }
    Ok((files, source.kind()))
}

fn missing(template: &Template) -> Error {
    Error::new(
        ErrorKind::Io,
        format!(
            "the {} template ({}) is not in the source",
            template.name, template.path
        ),
    )
}

/// The starter's `AGENTS.md`, `.env.example`, `README.md` and agent skill where the template has
/// none, and the starter's `.gitignore` lines it lacks (spec/service.md §2.1).
fn overlay(unpacked: &Path) -> Result<(), Error> {
    for (name, contents) in starter_files() {
        if !matches!(name, "AGENTS.md" | ".env.example" | "README.md")
            && !name.starts_with(".agents/")
        {
            continue;
        }
        let file = unpacked.join(name);
        if !file.exists() {
            write_new(&file, contents, name)?;
        }
    }
    let starter = STARTER
        .iter()
        .find(|(name, _)| *name == ".gitignore")
        .map(|(_, contents)| *contents)
        .unwrap_or_default();
    let file = unpacked.join(".gitignore");
    let own = match std::fs::read_to_string(&file) {
        Ok(own) => own,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return write_new(&file, starter.as_bytes(), ".gitignore");
        }
        Err(error) => return Err(Error::io(".gitignore", &error)),
    };
    let have: Vec<&str> = own.lines().map(str::trim).collect();
    let lacking: Vec<&str> = starter
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#') && !have.contains(line))
        .collect();
    if lacking.is_empty() {
        return Ok(());
    }
    let mut merged = own;
    if !merged.is_empty() && !merged.ends_with('\n') {
        merged.push('\n');
    }
    merged.push_str("\n# FX run records, cache, provider keys and packages\n");
    for line in lacking {
        merged.push_str(line);
        merged.push('\n');
    }
    std::fs::write(&file, merged).map_err(|error| Error::io(".gitignore", &error))
}

/// The files under `folder`, relative and `/`-separated.
fn list_files(folder: &Path, relative: &Path, files: &mut Vec<String>) -> Result<(), Error> {
    for entry in std::fs::read_dir(folder.join(relative))
        .map_err(|error| Error::io("the template", &error))?
    {
        let entry = entry.map_err(|error| Error::io("the template", &error))?;
        let path = relative.join(entry.file_name());
        if entry.path().is_dir() {
            list_files(folder, &path, files)?;
        } else {
            let parts: Vec<String> = path
                .components()
                .map(|part| part.as_os_str().to_string_lossy().into_owned())
                .collect();
            files.push(parts.join("/"));
        }
    }
    Ok(())
}

/// How much of a template has been written, against [`MAX_FILES`] and [`MAX_UNPACKED`].
#[derive(Default)]
struct Limits {
    files: usize,
    bytes: u64,
}

impl Limits {
    fn add(&mut self, size: u64) -> Result<(), Error> {
        self.files += 1;
        self.bytes = self.bytes.saturating_add(size);
        if self.files > MAX_FILES {
            return Err(refused(format!("it holds more than {MAX_FILES} files")));
        }
        if self.bytes > MAX_UNPACKED {
            return Err(refused(format!(
                "it holds more than {} MiB",
                MAX_UNPACKED / 1024 / 1024
            )));
        }
        Ok(())
    }
}

fn refused(why: impl std::fmt::Display) -> Error {
    Error::new(
        ErrorKind::Io,
        format!("the template was refused: {why}; nothing was written"),
    )
}

/// A `/`-separated relative path's parts, or `None` when it is absolute or holds `.` or `..`.
fn relative_parts(path: &str) -> Option<Vec<&str>> {
    let parts: Vec<&str> = path.split('/').collect();
    if parts
        .iter()
        .any(|part| part.is_empty() || *part == "." || *part == "..")
    {
        return None;
    }
    Some(parts)
}

/// Copies a template folder of a directory source, skipping [`SKIPPED`] and refusing links.
fn copy_tree(from: &Path, to: &Path, relative: &Path, limits: &mut Limits) -> Result<(), Error> {
    let entries =
        std::fs::read_dir(from.join(relative)).map_err(|error| Error::io("the source", &error))?;
    for entry in entries {
        let entry = entry.map_err(|error| Error::io("the source", &error))?;
        let name = entry.file_name();
        if SKIPPED.iter().any(|skipped| name == *skipped) {
            continue;
        }
        let path = relative.join(&name);
        let kind = entry
            .file_type()
            .map_err(|error| Error::io("the source", &error))?;
        if kind.is_dir() {
            std::fs::create_dir_all(to.join(&path))
                .map_err(|error| Error::io("the template", &error))?;
            copy_tree(from, to, &path, limits)?;
        } else if kind.is_file() {
            let bytes =
                std::fs::read(entry.path()).map_err(|error| Error::io("the source", &error))?;
            limits.add(bytes.len() as u64)?;
            write_new(&to.join(&path), &bytes, "the template")?;
        } else {
            return Err(refused(format!(
                "{} is a link or a special file",
                path.display()
            )));
        }
    }
    Ok(())
}

/// Unpacks the template's folder of a gzip-compressed tar archive whose entries lie under one
/// top-level folder (spec/service.md §2.1). The rest of the archive is skipped unread.
fn unpack(bytes: &[u8], template: &Template, to: &Path, limits: &mut Limits) -> Result<(), Error> {
    let wanted = relative_parts(&template.path).ok_or_else(|| missing(template))?;
    let unreadable = |_| {
        Error::new(
            ErrorKind::Io,
            "the template archive is not a readable .tar.gz",
        )
    };
    let mut archive = tar::Archive::new(flate2::read::GzDecoder::new(bytes));
    let mut top: Option<String> = None;
    let mut found = false;
    for entry in archive.entries().map_err(unreadable)? {
        let mut entry = entry.map_err(unreadable)?;
        let kind = entry.header().entry_type();
        if kind.is_pax_global_extensions() {
            continue;
        }
        let path = entry.path().map_err(unreadable)?.into_owned();
        let mut parts = Vec::new();
        for component in path.components() {
            match component {
                Component::Normal(part) => parts.push(part.to_string_lossy().into_owned()),
                Component::CurDir => {}
                _ => parts.push(String::from("..")),
            }
        }
        let Some(first) = parts.first() else { continue };
        match &top {
            None => top = Some(first.clone()),
            Some(top) if top != first => {
                return Err(refused("the archive has more than one top-level folder"));
            }
            Some(_) => {}
        }
        let rest = &parts[1..];
        if rest.len() < wanted.len() || rest[..wanted.len()] != wanted[..] {
            continue;
        }
        found = true;
        let inside = &rest[wanted.len()..];
        if inside.is_empty() {
            continue;
        }
        if inside.iter().any(|part| part == "..") {
            return Err(refused(format!("{} leaves its folder", inside.join("/"))));
        }
        let target = inside
            .iter()
            .fold(to.to_path_buf(), |path, part| path.join(part));
        if kind.is_dir() {
            std::fs::create_dir_all(&target).map_err(|error| Error::io("the template", &error))?;
        } else if kind.is_file() || kind == tar::EntryType::Continuous {
            let size = entry.header().size().map_err(unreadable)?;
            limits.add(size)?;
            let mut contents = Vec::with_capacity(size.min(MAX_UNPACKED) as usize);
            entry
                .by_ref()
                .take(MAX_UNPACKED + 1)
                .read_to_end(&mut contents)
                .map_err(|error| Error::io("the template archive", &error))?;
            write_new(&target, &contents, "the template")?;
        } else {
            return Err(refused(format!(
                "{} is a link or a special file",
                inside.join("/")
            )));
        }
    }
    if !found {
        return Err(missing(template));
    }
    Ok(())
}

/// Fetches an archive once (spec/service.md §2.1): the download lane, no credential, no redirect,
/// no retry; anything but 200 is refused. `GRIDA_FX_NETWORK=off` refuses it before it is sent.
fn download(url: &str) -> Result<Vec<u8>, Error> {
    let network = grida_fx_providers::live::Network::from_env(&|name| std::env::var(name).ok());
    if network == grida_fx_providers::live::Network::Off {
        return Err(Error::new(
            ErrorKind::Io,
            "init --template downloads its template, and the network is off (GRIDA_FX_NETWORK=off)",
        ));
    }
    let transport = HttpTransport::new(HttpConfig::default()).map_err(Error::internal)?;
    let request = HttpRequest {
        method: Method::Get,
        url: url.to_string(),
        headers: vec![("accept".into(), "application/gzip, */*".into())],
        credential: None,
        body: Body::Empty,
        timeout: DOWNLOAD_TIMEOUT,
        max_response_bytes: MAX_DOWNLOAD,
        lane: Lane::Download,
    };
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|error| Error::io("the download", &error))?;
    let response = runtime.block_on(transport.send(request)).map_err(|error| {
        Error::new(
            ErrorKind::Io,
            format!("the template could not be downloaded: {}", error.reason),
        )
    })?;
    if response.status != 200 {
        return Err(Error::new(
            ErrorKind::Io,
            format!(
                "the template download returned HTTP {}; this FX version's templates may not be \
                 published yet",
                response.status
            ),
        ));
    }
    Ok(response.body)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_embedded_index_is_well_formed_and_names_examples() {
        let templates = templates().unwrap();
        assert!(!templates.is_empty());
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        for template in templates {
            assert!(
                root.join(&template.path).join("fx.yaml").is_file(),
                "{}",
                template.path
            );
        }
    }

    #[test]
    fn every_skill_is_embedded_under_agents_skills() {
        let names: Vec<&str> = SKILLS.iter().map(|(name, _)| *name).collect();
        assert!(names.contains(&".agents/skills/grida-fx/SKILL.md"));
        assert!(names.contains(&".agents/skills/grida-fx/references/onboarding.md"));
        // skills/README.md describes the folder; it is not a skill's file.
        assert!(!names.contains(&".agents/skills/README.md"));
    }

    #[test]
    fn the_release_url_names_this_version_s_tag() {
        assert_eq!(
            release_url(),
            format!("https://codeload.github.com/gridaco/fx/tar.gz/v{ENGINE_VERSION}")
        );
    }

    #[test]
    fn a_path_is_relative_without_dots() {
        assert_eq!(
            relative_parts("examples/hello"),
            Some(vec!["examples", "hello"])
        );
        assert_eq!(relative_parts("/examples"), None);
        assert_eq!(relative_parts("examples/../x"), None);
        assert_eq!(relative_parts("examples//x"), None);
    }
}
